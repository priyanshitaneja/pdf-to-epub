#!/usr/bin/env node
/**
 * Copy pdf.js's runtime data files into `public/pdfjs/`.
 *
 * pdf.js fetches cMaps and the standard-font programs over HTTP at runtime. Without them, CJK
 * text and any PDF relying on the base-14 fonts extract as garbled output — and nothing errors,
 * which is what makes this worth a dedicated, verified step.
 *
 * `public/` rather than a copy plugin, because Vite serves `public/` in dev *and* copies it into
 * `dist/` on build, so one mechanism covers both. vite-plugin-static-copy was doing neither
 * correctly here: it preserved the full `node_modules/pdfjs-dist/...` source path inside the
 * destination and served nothing at all in dev, while still reporting "Copied 185 items".
 *
 * The output is gitignored and regenerated by `predev`/`prebuild`, so the binaries never enter
 * the repository.
 */
import { cp, mkdir, readdir, rm } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const targets = [
  { from: 'node_modules/pdfjs-dist/cmaps', to: 'public/pdfjs/cmaps' },
  { from: 'node_modules/pdfjs-dist/standard_fonts', to: 'public/pdfjs/standard_fonts' },
];

let failed = false;

for (const { from, to } of targets) {
  const src = join(root, from);
  const dest = join(root, to);

  let entries;
  try {
    entries = await readdir(src);
  } catch {
    console.error(`[sync-pdfjs-assets] missing source: ${from} — is pdfjs-dist installed?`);
    failed = true;
    continue;
  }

  // Clear first so a pdfjs-dist upgrade cannot leave stale files behind.
  await rm(dest, { recursive: true, force: true });
  await mkdir(dest, { recursive: true });
  await cp(src, dest, { recursive: true });

  const copied = await readdir(dest);
  if (copied.length !== entries.length) {
    console.error(`[sync-pdfjs-assets] ${to}: expected ${entries.length} files, got ${copied.length}`);
    failed = true;
    continue;
  }
  console.log(`[sync-pdfjs-assets] ${to} <- ${copied.length} files`);
}

if (failed) process.exit(1);
